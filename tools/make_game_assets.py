#!/usr/bin/env python3
"""Write the art of the Game page as LVGL 8 images: src/game_assets.c and src/game_assets.h.

Usage: tools/make_game_assets.py                  (needs Pillow)
       tools/make_game_assets.py --preview DIR    (also writes one PNG per image, for a look)

The art itself is in tools/game_art.py (original pixel art, drawn with code). To change the look, edit
that file and run this script again. Pixel formats (see src/lv_conf.h: LV_COLOR_16_SWAP = 1):
  opaque images  LV_IMG_CF_TRUE_COLOR        2 bytes per pixel: RGB565 high byte, low byte
  sprites        LV_IMG_CF_TRUE_COLOR_ALPHA  3 bytes per pixel: the same two bytes, then alpha
"""
import argparse
import os

import game_art

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Where the jetpack flame hangs, in the hero image: top centre of the flame.
NOZZLE_X, NOZZLE_Y = 10, 46

GROUPS = (("flame", 3), ("coin", 6), ("node", 2), ("mflame", 2), ("sci", 2))


def pixels(img, opaque):
    data = bytearray()
    for r, g, b, a in zip(*[iter(img.tobytes())] * 4):
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((c >> 8, c & 0xFF)) if opaque else bytes((c >> 8, c & 0xFF, a))
    return data


def write_c(path, images):
    out = ["/* Generated by tools/make_game_assets.py. Do not edit. */", '#include "game_assets.h"', ""]
    for name, (img, opaque) in images.items():
        data = pixels(img, opaque)
        out.append(f"static const uint8_t {name}_map[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
        out.append("};")
        cf = "LV_IMG_CF_TRUE_COLOR" if opaque else "LV_IMG_CF_TRUE_COLOR_ALPHA"
        out.append(f"const lv_img_dsc_t ga_{name} = {{")
        out.append(f"    .header = {{.cf = {cf}, .always_zero = 0, .reserved = 0, .w = {img.width}, .h = {img.height}}},")
        out.append(f"    .data_size = {len(data)},\n    .data = {name}_map,\n}};\n")
    for group, count in GROUPS:
        out.append(f"const lv_img_dsc_t *const ga_{group}[{count}] = {{" +
                   ", ".join(f"&ga_{group}{i}" for i in range(count)) + "};")
    open(path, "w").write("\n".join(out) + "\n")


def write_h(path, images):
    size = {n: i.size for n, (i, _) in images.items()}
    h = ["/* Generated by tools/make_game_assets.py. Do not edit. */", "#pragma once", "", "#include <lvgl.h>", "",
         "/* Sizes and anchor points of the art, in pixels. */",
         f"#define GA_WALL_W {size['wall'][0]} /* the wall repeats every GA_WALL_W px */",
         f"#define GA_WALL_H {size['wall'][1]}",
         f"#define GA_STRIP_W {size['ceil'][0]} /* the ceiling and floor strips repeat every GA_STRIP_W px */",
         f"#define GA_STRIP_H {size['ceil'][1]}",
         f"#define GA_SHADOW_W {size['shadow'][0]}", f"#define GA_SHADOW_H {size['shadow'][1]}",
         f"#define GA_HERO_W {size['hero_fly'][0]}", f"#define GA_HERO_H {size['hero_fly'][1]}",
         f"#define GA_DEAD_W {size['hero_dead'][0]}", f"#define GA_DEAD_H {size['hero_dead'][1]}",
         f"#define GA_NOZZLE_X {NOZZLE_X} /* flame top, centre, inside the hero image */",
         f"#define GA_NOZZLE_Y {NOZZLE_Y}",
         f"#define GA_FLAME_W {size['flame0'][0]}", f"#define GA_FLAME_H {size['flame0'][1]}",
         f"#define GA_COIN {size['coin0'][0]}", f"#define GA_NODE {size['node0'][0]}",
         f"#define GA_MISSILE_W {size['missile'][0]}", f"#define GA_MISSILE_H {size['missile'][1]}",
         f"#define GA_MFLAME_W {size['mflame0'][0]}", f"#define GA_MFLAME_H {size['mflame0'][1]}",
         f"#define GA_WARN_W {size['warn'][0]}", f"#define GA_WARN_H {size['warn'][1]}",
         f"#define GA_SCI_W {size['sci0'][0]}", f"#define GA_SCI_H {size['sci0'][1]}", ""]
    for name in images:
        if not name[-1].isdigit():
            h.append(f"extern const lv_img_dsc_t ga_{name};")
    h.append("")
    for group, count in GROUPS:
        h.append(f"extern const lv_img_dsc_t *const ga_{group}[{count}];")
    open(path, "w").write("\n".join(h) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", metavar="DIR", help="also write a PNG per image into DIR")
    args = ap.parse_args()

    images = game_art.build()
    write_c(os.path.join(ROOT, "src", "game_assets.c"), images)
    write_h(os.path.join(ROOT, "src", "game_assets.h"), images)
    total = sum(len(pixels(i, o)) for i, o in images.values())
    print(f"{len(images)} images, {total} bytes of pixel data")
    if args.preview:
        os.makedirs(args.preview, exist_ok=True)
        for name, (img, _) in images.items():
            img.save(os.path.join(args.preview, f"{name}.png"))


if __name__ == "__main__":
    main()
