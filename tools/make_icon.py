#!/usr/bin/env python3
"""Rasterize an SVG into an LVGL 8 image (src/<name>.c). Needs rsvg-convert and Pillow.

Usage: tools/make_icon.py tools/assets/claude_icon.svg src/claude_icon.c --size 120

Pixel format: LV_IMG_CF_TRUE_COLOR_ALPHA with LV_COLOR_16_SWAP=1 (see src/lv_conf.h),
so each pixel is 3 bytes: RGB565 high byte, RGB565 low byte, alpha.
"""
import argparse
import io
import os
import subprocess

from PIL import Image


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("svg")
    ap.add_argument("output")
    ap.add_argument("--size", type=int, default=120, help="width and height in pixels")
    args = ap.parse_args()

    png = subprocess.run(["rsvg-convert", "-w", str(args.size), "-h", str(args.size), args.svg],
                         check=True, capture_output=True).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    w, h = img.size

    data = bytearray()
    for r, g, b, a in zip(*[iter(img.tobytes())] * 4):
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((c >> 8, c & 0xFF, a))

    name = os.path.splitext(os.path.basename(args.output))[0]
    with open(args.output, "w") as f:
        f.write(f"/* Generated by tools/make_icon.py from {os.path.basename(args.svg)}. Do not edit. */\n")
        f.write('#include <lvgl.h>\n\n')
        f.write(f"static const uint8_t {name}_map[] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write(f"const lv_img_dsc_t {name} = {{\n")
        f.write(f"    .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = {w}, .h = {h}}},\n")
        f.write(f"    .data_size = {len(data)},\n    .data = {name}_map,\n}};\n")


if __name__ == "__main__":
    main()
